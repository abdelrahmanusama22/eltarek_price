<?php

declare(strict_types=1);

namespace App\Policies;

use Illuminate\Foundation\Auth\User as AuthUser;
use Spatie\Activitylog\Models\Activity;
use Illuminate\Auth\Access\HandlesAuthorization;

class ActivityPolicy
{
    use HandlesAuthorization;
    
    public function viewAny(AuthUser $authUser): bool
    {
        return $authUser->can('ViewAny:Activity');
    }

    public function view(AuthUser $authUser, Activity $activity): bool
    {
        return $authUser->can('View:Activity');
    }

    /**
     * Determine whether the user can create activities.
     * IMMUTABILITY: Activities are strictly generated by system event listeners.
     */
    public function create(AuthUser $authUser): bool
    {
        return false;
    }

    /**
     * Determine whether the user can update an activity.
     * IMMUTABILITY: Historical audit records can never be mutated.
     */
    public function update(AuthUser $authUser, Activity $activity): bool
    {
        return false;
    }

    /**
     * Determine whether the user can delete an activity.
     * IMMUTABILITY: Price history and audit records can never be deleted under any circumstances.
     */
    public function delete(AuthUser $authUser, Activity $activity): bool
    {
        return false;
    }

    /**
     * Determine whether the user can bulk delete activities.
     * IMMUTABILITY: Bulk deletion is strictly prohibited.
     */
    public function deleteAny(AuthUser $authUser): bool
    {
        return false;
    }

    public function restore(AuthUser $authUser, Activity $activity): bool
    {
        return false;
    }

    /**
     * Determine whether the user can permanently force delete an activity.
     * IMMUTABILITY: Force delete is strictly prohibited.
     */
    public function forceDelete(AuthUser $authUser, Activity $activity): bool
    {
        return false;
    }

    /**
     * Determine whether the user can bulk force delete activities.
     * IMMUTABILITY: Bulk force delete is strictly prohibited.
     */
    public function forceDeleteAny(AuthUser $authUser): bool
    {
        return false;
    }

    public function restoreAny(AuthUser $authUser): bool
    {
        return false;
    }

    public function replicate(AuthUser $authUser, Activity $activity): bool
    {
        return false;
    }

    public function reorder(AuthUser $authUser): bool
    {
        return false;
    }

    public function manageCrmId(AuthUser $authUser, Activity $activity): bool
    {
        return false;
    }


}